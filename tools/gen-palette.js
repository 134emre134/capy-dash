// Collects every #rrggbb colour used in www/js/*.js into www/js/palette.js.
// The renderer snaps every pixel to this palette. Run after adding new colours:
//   node tools/gen-palette.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'www', 'js');
const set = new Set(['#000000', '#ffffff']);
for (const f of fs.readdirSync(dir)) {
  if (!f.endsWith('.js') || f === 'palette.js') continue;
  for (const m of fs.readFileSync(path.join(dir, f), 'utf8').matchAll(/#[0-9a-fA-F]{6}\b/g)) set.add(m[0].toLowerCase());
}
const list = [...set].sort();
fs.writeFileSync(path.join(dir, 'palette.js'), "'use strict';\n// generated by tools/gen-palette.js — do not edit by hand\nconst PALETTE_HEX = " + JSON.stringify(list) + ';\n');
console.log(list.length + ' colours');
